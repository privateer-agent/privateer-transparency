const mongoose = require('mongoose');

const userMemorySchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    // AES-256-GCM encrypted content: JSON string { iv: base64, ct: base64 }
    encryptedContent: {
      type: String,
      required: true,
    },
    // explicit = user said "remember that…"; auto = AI detected important fact
    source: {
      type: String,
      enum: ['explicit', 'auto'],
      default: 'explicit',
    },
    isActive: {
      type: Boolean,
      default: true,
      index: true,
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model('UserMemory', userMemorySchema);
